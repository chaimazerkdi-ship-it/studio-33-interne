-- Photos des fournisseurs (demande de Chaima, 07/11/2026).
--
-- Les photos prises dans les magasins des fournisseurs (ou ailleurs) sont
-- rangees avec leur fiche. Le fichier est dans le stockage (bucket admin-docs,
-- dossier fournisseurs/<id>/), jamais en base64 dans la table : la table ne
-- garde que le chemin, une vignette de 420 px et une legende facultative.
-- Ajout seul : rien d'existant n'est modifie.

create table if not exists public.mat_supplier_photos (
  id          bigint generated by default as identity primary key,
  supplier_id bigint not null references public.mat_suppliers(id) on delete cascade,
  file_path   text not null check (file_path like 'fournisseurs/%'),
  thumb       text check (thumb is null or (thumb like 'data:image/%' and length(thumb) < 200000)),
  note        text check (note is null or length(note) <= 500),
  added_by    text,
  created_at  timestamptz not null default now()
);

create index if not exists mat_supplier_photos_supplier_idx
  on public.mat_supplier_photos (supplier_id);

alter table public.mat_supplier_photos enable row level security;

-- Meme regle que mat_suppliers : les membres connectes, personne sans compte
create policy mat_supplier_photos_membres on public.mat_supplier_photos
  for all to authenticated using (true) with check (true);
