-- Notifications sur le telephone des clients (demande de Chaima, 10/11/2026).
--
-- Dans son espace, le client touche « Me prevenir des nouveaux documents » :
-- son navigateur donne une adresse d'envoi (abonnement Web Push), gardee ici
-- avec le projet. Quand le cabinet partage un document, la fonction send-push
-- envoie la notification a ces adresses.
--
-- Ecriture : seulement par les fonctions serveur (client-portal, send-push),
-- avec la cle serveur. Lecture : l'admin et les co-admins (nombre d'appareils
-- abonnes dans la fenetre de partage). Personne sans compte.
-- Ajout seul : rien d'existant n'est modifie.

create table if not exists public.portal_push_subscriptions (
  id           bigint generated by default as identity primary key,
  project_id   bigint not null references public.projects(id) on delete cascade,
  endpoint     text not null check (endpoint like 'https://%' and length(endpoint) <= 1000),
  p256dh       text not null check (length(p256dh) <= 200),
  auth         text not null check (length(auth) <= 100),
  ua           text check (ua is null or length(ua) <= 200),
  created_at   timestamptz not null default now(),
  last_sent_at timestamptz,
  -- Un meme telephone peut suivre plusieurs projets (un client, deux chantiers)
  constraint portal_push_subscriptions_projet_adresse unique (project_id, endpoint)
);

create index if not exists portal_push_subscriptions_project_idx
  on public.portal_push_subscriptions (project_id);

alter table public.portal_push_subscriptions enable row level security;

create policy portal_push_lecture_admin on public.portal_push_subscriptions
  for select to authenticated using (public.s33_is_admin());
